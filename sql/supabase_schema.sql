-- CREATE RLS POLICIES

-- RLS Policies for users table
CREATE POLICY "Users can view all users" 
  ON users FOR SELECT 
  USING (true);

CREATE POLICY "Users can insert their own profile" 
  ON users FOR INSERT 
  TO authenticated
  WITH CHECK (auth.uid() = id);

CREATE POLICY "Users can update their own profile" 
  ON users FOR UPDATE 
  USING (auth.uid() = id)
  WITH CHECK (auth.uid() = id);

-- RLS Policies for questions table
CREATE POLICY "Anyone can read questions" 
  ON questions FOR SELECT 
  USING (true);

CREATE POLICY "Only admins can modify questions" 
  ON questions FOR ALL 
  USING (
    EXISTS (
      SELECT 1 FROM users 
      WHERE id = auth.uid() 
      AND role = 'admin'
    )
  );

-- RLS Policies for answers table
CREATE POLICY "Users can insert their own answers" 
  ON answers FOR INSERT 
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can view own answers" 
  ON answers FOR SELECT 
  USING (auth.uid() = user_id);

CREATE POLICY "Admins can view all answers" 
  ON answers FOR SELECT 
  USING (is_admin());

-- RLS Policies for quiz_sessions table
CREATE POLICY "Users can view their own sessions" 
  ON quiz_sessions FOR SELECT 
  USING (auth.uid() = user_id);

CREATE POLICY "Users can create their own sessions" 
  ON quiz_sessions FOR INSERT 
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own sessions" 
  ON quiz_sessions FOR UPDATE 
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Admins can view all sessions" 
  ON quiz_sessions FOR SELECT 
  USING (
    EXISTS (
      SELECT 1 FROM users 
      WHERE id = auth.uid() 
      AND role = 'admin'
    )
  );

-- RLS Policies for quiz_session_questions table
CREATE POLICY "Users can view their session questions" 
  ON quiz_session_questions FOR SELECT 
  USING (
    EXISTS (
      SELECT 1 FROM quiz_sessions 
      WHERE quiz_sessions.id = session_id 
      AND quiz_sessions.user_id = auth.uid()
    )
  );

CREATE POLICY "Users can insert their session questions" 
  ON quiz_session_questions FOR INSERT 
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM quiz_sessions 
      WHERE quiz_sessions.id = session_id 
      AND quiz_sessions.user_id = auth.uid()
    )
  );

CREATE POLICY "Admins can view all session questions" 
  ON quiz_session_questions FOR SELECT 
  USING (
    EXISTS (
      SELECT 1 FROM users 
      WHERE id = auth.uid() 
      AND role = 'admin'
    )
  );

-- RLS Policies for broadcast state
CREATE POLICY "Anyone can read broadcast state" 
  ON public_broadcast_state FOR SELECT 
  TO anon, authenticated
  USING (true);

CREATE POLICY "Only admins can update broadcast state" 
  ON public_broadcast_state FOR UPDATE 
  USING (
    EXISTS (
      SELECT 1 FROM users 
      WHERE id = auth.uid() 
      AND role = 'admin'
    )
  );

